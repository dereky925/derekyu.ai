export const photoAlbums: PhotoAlbum[] = photos.reduce<PhotoAlbum[]>((albums, photo) => {
  const last = albums[albums.length - 1];
  if (
    last &&
    last.location === photo.location &&
    last.year === photo.year &&
    last.month === photo.month
  ) {
    last.photos.push(photo);
    return albums;
  }
  albums.push({
    location: photo.location,
    year: photo.year,
    month: photo.month,
    photos: [photo],
  });
  return albums;
}, []);

